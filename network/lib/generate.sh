#!/usr/bin/env bash
#
# Listing L1.4: generates build/ from the network file: the secrets file, two
# Compose files and configtx.yaml. Run it again after editing the network file;
# the secrets are kept.
set -euo pipefail
source "$(dirname "$0")/common.sh"
mkdir -p "$BUILD"

# Bootstrap passwords of every CA and CouchDB, readable by the owner only
if [ ! -s "$BUILD/.secrets/network.env" ]; then
  (umask 077; mkdir -p "$BUILD/.secrets"
   for o in $ALL_ORGS; do
     for v in CA TLSCA COUCHDB; do
       echo "${o^^}_${v}_PW=$(openssl rand -hex 16)"
     done
   done > "$BUILD/.secrets/network.env")
fi

ca_service() {  # ca_service KIND PORT: an identity or TLS CA for $ORG
  local kind=$1 port=$2 var=${ORG^^}_${1^^}_PW
  cat <<EOF

  $kind-$ORG:
    image: hyperledger/fabric-ca:1.5.22
    container_name: $kind.$DOMAIN
    environment:
      FABRIC_CA_HOME: /etc/hyperledger/fabric-ca-server
      FABRIC_CA_SERVER_CA_NAME: $kind-$ORG
      FABRIC_CA_SERVER_PORT: $port
      FABRIC_CA_SERVER_TLS_ENABLED: "true"
      FABRIC_CA_SERVER_CSR_CN: $kind-$ORG
      FABRIC_CA_SERVER_CSR_HOSTS: $kind.$DOMAIN,localhost
      FABRIC_CA_SERVER_OPERATIONS_LISTENADDRESS: 0.0.0.0:$((port + 400))
      BOOTSTRAP_PW: \${$var:?run network.sh generate}
    command: sh -c 'fabric-ca-server start -b caadmin:\$\$BOOTSTRAP_PW'
    volumes:
      - ./organizations/$ORG/$kind:/etc/hyperledger/fabric-ca-server
    ports:
      - "$port:$port"
    networks: [$PROJECT]
EOF
}

{
  echo "# Generated by network.sh from $(basename "$NETFILE"). Do not edit."
  echo "name: $PROJECT"
  echo "services:"
  for o in $ALL_ORGS; do
    org "$o"; ca_service ca $((BASE + 54)); ca_service tlsca $((BASE + 55))
  done
  echo; echo "networks:"; echo "  $PROJECT:"; echo "    name: $PROJECT"
} > "$BUILD/compose-ca.yaml"

net_services() {  # the orderer, CouchDB, peer and chaincode server of $ORG
  local couch=couchdb.$DOMAIN pw=${ORG^^}_COUCHDB_PW
  if [ "$ORDERER_NODE" != false ]; then cat <<EOF     # true, or later

  orderer0-$ORG:
    image: hyperledger/fabric-orderer:3.1.5
    container_name: orderer0.$DOMAIN
    environment:
      <<: *orderer-env
      ORDERER_GENERAL_LISTENPORT: $((BASE + 50))
      ORDERER_GENERAL_LOCALMSPID: $MSP
      ORDERER_ADMIN_LISTENADDRESS: 0.0.0.0:$((BASE + 53))
      ORDERER_OPERATIONS_LISTENADDRESS: 0.0.0.0:$((BASE + 444))
    command: orderer
    volumes:
      - ./organizations/$ORG/orderer0:/etc/hyperledger/crypto:ro
      - orderer0.$DOMAIN:/var/hyperledger/production/orderer
    ports: ["$((BASE + 50)):$((BASE + 50))", "$((BASE + 53)):$((BASE + 53))",
            "$((BASE + 444)):$((BASE + 444))"]
    networks: [$PROJECT]
EOF
  fi
  if [ "$STATEDB" = CouchDB ]; then cat <<EOF

  couchdb-$ORG:
    image: couchdb:3.4.2
    container_name: $couch
    environment:
      COUCHDB_USER: admin
      COUCHDB_PASSWORD: \${$pw:?run network.sh generate}
    volumes:
      - $couch:/opt/couchdb/data
    ports: ["127.0.0.1:$((BASE + 84)):5984"]     # this machine only
    networks: [$PROJECT]
EOF
  fi
  cat <<EOF

  peer0-$ORG:
    image: hyperledger/fabric-peer:3.1.5
    container_name: peer0.$DOMAIN
    environment:
      <<: *peer-env
      CORE_PEER_ID: peer0.$DOMAIN
      CORE_PEER_LOCALMSPID: $MSP
      CORE_PEER_ADDRESS: peer0.$DOMAIN:$((BASE + 51))
      CORE_PEER_LISTENADDRESS: 0.0.0.0:$((BASE + 51))
      CORE_PEER_CHAINCODEADDRESS: peer0.$DOMAIN:$((BASE + 52))
      CORE_PEER_CHAINCODELISTENADDRESS: 0.0.0.0:$((BASE + 52))
      CORE_PEER_GOSSIP_EXTERNALENDPOINT: peer0.$DOMAIN:$((BASE + 51))
      CORE_PEER_GOSSIP_BOOTSTRAP: peer0.$DOMAIN:$((BASE + 51))
      CORE_OPERATIONS_LISTENADDRESS: 0.0.0.0:$((BASE + 443))
      CORE_LEDGER_SNAPSHOTS_ROOTDIR: /var/hyperledger/snapshots/$ORG
EOF
  if [ "$STATEDB" = CouchDB ]; then cat <<EOF
      CORE_LEDGER_STATE_STATEDATABASE: CouchDB
      CORE_LEDGER_STATE_COUCHDBCONFIG_COUCHDBADDRESS: $couch:5984
      CORE_LEDGER_STATE_COUCHDBCONFIG_USERNAME: admin
      CORE_LEDGER_STATE_COUCHDBCONFIG_PASSWORD: \${$pw:?run network.sh generate}
    depends_on: [couchdb-$ORG]
EOF
  fi
  cat <<EOF
    command: peer node start
    volumes:
      - ./organizations/$ORG/peer0:/etc/hyperledger/crypto:ro
      - peer0.$DOMAIN:/var/hyperledger/production
      - ./snapshots:/var/hyperledger/snapshots      # shared, for Lab 4
    ports: ["$((BASE + 51)):$((BASE + 51))", "$((BASE + 443)):$((BASE + 443))"]
    networks: [$PROJECT]

  $CC-$ORG:               # chaincode server for $MSP
    build: $CC_PATH
    image: $CC-chaincode:$CC_VERSION
    container_name: $CC.$DOMAIN
    working_dir: /usr/src/app
    environment:
      CHAINCODE_ID: \${CC_PACKAGE_ID_${ORG^^}:-set by network.sh deploy}
      CHAINCODE_SERVER_ADDRESS: 0.0.0.0:$((BASE + 99))
    command: >-
      sh -c 'exec ./node_modules/.bin/fabric-chaincode-node server
      --chaincode-address=\$\$CHAINCODE_SERVER_ADDRESS
      --chaincode-id=\$\$CHAINCODE_ID
      --chaincode-tls-cert-file=/etc/hyperledger/crypto/server.crt
      --chaincode-tls-key-file=/etc/hyperledger/crypto/server.key'
    volumes:
      - ./organizations/$ORG/$CC/tls:/etc/hyperledger/crypto:ro
    networks: [$PROJECT]
EOF
}

{
  echo "# Generated by network.sh from $(basename "$NETFILE"). Do not edit."
  echo "name: $PROJECT"
  cat "$NET/templates/compose-net-head.yaml"; echo; echo "services:"
  for o in $ALL_ORGS; do org "$o"; net_services; done
  echo; echo "volumes:"
  for o in $ALL_ORGS; do
    org "$o"
    [ "$ORDERER_NODE" != false ] && echo "  orderer0.$DOMAIN:"
    [ "$STATEDB" = CouchDB ] && echo "  couchdb.$DOMAIN:"
    echo "  peer0.$DOMAIN:"
  done
  echo; echo "networks:"; echo "  $PROJECT:"; echo "    name: $PROJECT"
} > "$BUILD/compose-net.yaml"

org_section() {  # one organization in configtx.yaml
  cat <<EOF
  - &$MSP
    Name: $MSP
    ID: $MSP
    MSPDir: organizations/$ORG/msp
    Policies:
      Readers: {Type: Signature, Rule: "OR('$MSP.member')"}
      Writers: {Type: Signature,
                Rule: "OR('$MSP.admin', '$MSP.client', '$MSP.orderer')"}
      Admins: {Type: Signature, Rule: "OR('$MSP.admin')"}
      Endorsement: {Type: Signature, Rule: "OR('$MSP.peer')"}
EOF
  [ "$ORDERER_NODE" = true ] &&
    printf '    OrdererEndpoints: [orderer0.%s:%s]\n' "$DOMAIN" $((BASE + 50))
  printf '    AnchorPeers: [{Host: peer0.%s, Port: %s}]\n' "$DOMAIN" $((BASE + 51))
}

{
  echo "# Generated by network.sh from $(basename "$NETFILE"). Do not edit."
  echo "---"; echo "Organizations:"
  for o in $ALL_ORGS; do org "$o"; org_section; done
  cat "$NET/templates/configtx-head.yaml"
  echo "  EtcdRaft:"; echo "    Consenters:"
  for o in $FOUNDERS; do
    org "$o"; [ "$ORDERER_NODE" = true ] || continue
    t=organizations/$ORG/orderer0/tls/server.crt
    printf '      - {Host: orderer0.%s, Port: %s,\n' "$DOMAIN" $((BASE + 50))
    printf '         ClientTLSCert: %s, ServerTLSCert: %s}\n' "$t" "$t"
  done
  cat "$NET/templates/configtx-tail.yaml"
  echo "  Channel:"
  echo "    <<: *ChannelDefaults"
  echo "    Orderer:"; echo "      <<: *OrdererDefaults"
  echo "      Organizations:"
  for o in $FOUNDERS; do
    org "$o"; [ "$ORDERER_NODE" = true ] && echo "        - *$MSP"
  done
  echo "      Capabilities: *OrdererCapabilities"
  echo "    Application:"; echo "      <<: *ApplicationDefaults"
  echo "      Organizations:"
  for o in $FOUNDERS; do org "$o"; echo "        - *$MSP"; done
  echo "      Capabilities: *ApplicationCapabilities"
} > "$BUILD/configtx.yaml"

echo "generated in $BUILD:"
echo "  compose-ca.yaml compose-net.yaml configtx.yaml .secrets/network.env"
echo "  state database: $STATEDB"
